#include "./ft_ssl_md5.h"

void    ft_init_k(uint32_t k[64])
{
        int     i;

        i = 0;
        while (i < 64)
        {
                k[i] = (uint32_t)(fabs(sin(i + 1)) * 4294967296.0);
                i++;
        }
}

